TRANSLATIONS = {"en": ENGLISH, "de": GERMAN, "ru": RUSSIAN}


@dataclass(slots=True)
class Translator:
    """Resolve stable translation keys with a predictable English fallback."""

    language: str = DEFAULT_LANGUAGE

    def __post_init__(self) -> None:
        if self.language not in TRANSLATIONS:
            self.language = DEFAULT_LANGUAGE

    def set_language(self, language: str) -> None:
        self.language = language if language in TRANSLATIONS else DEFAULT_LANGUAGE

    def tr(self, key: str, **values: object) -> str:
        template = TRANSLATIONS[self.language].get(key, ENGLISH.get(key, key))
        return template.format(**values)

    def books(self, count: int) -> str:
        if self.language == "ru":
            last_two = count % 100
            last = count % 10
            if last == 1 and last_two != 11:
                key = "book.one"
            elif last in (2, 3, 4) and last_two not in (12, 13, 14):
                key = "book.few"
            else:
                key = "book.other"
        else:
            key = "book.one" if count == 1 else "book.other"
        return self.tr(key, count=count)

    def user_message(self, message: str) -> str:
        """Translate known stable service messages without changing service APIs."""
        key = USER_MESSAGE_KEYS.get(message)
        if key is not None:
            return self.tr(key)
        prefix = "Calibre could not convert this book."
        if message.startswith(prefix):
            translated = self.tr("service.calibre_convert_failed")
            return translated + message[len(prefix) :]
        return message


